/** Короткий идентификатор статьи словаря: для нескольких слов есть понятные ссылки gloss-... */
private fun glossId(de: String, i: Int): String {
    val key = when {
        de.startsWith("Lieferschein") -> "lieferschein"
        de.startsWith("NVE") -> "nve"
        de.startsWith("GTIN") -> "gtin"
        de.startsWith("Ladeeinheit") -> "le"
        de.startsWith("Abrüsten") -> "abruesten"
        de.startsWith("Durchgangsinventur") -> "durch"
        de.startsWith("Ladeliste") -> "ladeliste"
        else -> "w" + i
    }
    return "gloss-" + key
}

private fun normH(s: String): String = s.lowercase().replace('ё', 'е')

private class HelpHit(val a: HelpArticle, val score: Int, val snippet: String)

private fun helpTokens(q: String): List<String> =
    normH(q).split(' ', '\t', ',', ';').filter { it.isNotBlank() }

private fun articleText(a: HelpArticle): String = a.lead + " " + a.blocks.joinToString(" ") { it.text }

private fun snippetOf(a: HelpArticle, tokens: List<String>): String {
    if (tokens.isEmpty()) return a.lead
    val first = tokens[0]
    val sources = ArrayList<String>()
    sources.add(a.lead)
    for (b in a.blocks) sources.add(b.text)
    for (src in sources) {
        val idx = normH(src).indexOf(first)
        if (idx >= 0) {
            val from = (idx - 50).coerceAtLeast(0)
            val to = (idx + 100).coerceAtMost(src.length)
            val head = if (from > 0) "…" else ""
            val tail = if (to < src.length) "…" else ""
            return head + src.substring(from, to) + tail
        }
    }
    return a.lead
}

private fun searchHelp(q: String): List<HelpHit> {
    val tokens = helpTokens(q)
    if (tokens.isEmpty()) return emptyList()
    val out = ArrayList<HelpHit>()
    for (a in HELP_ARTICLES) {
        val title = normH(a.title)
        val keys = normH(a.keys)
        val body = normH(articleText(a))
        var score = 0
        var ok = true
        for (t in tokens) {
            var s = 0
            if (title.contains(t)) s += 10
            if (keys.contains(t)) s += 6
            if (body.contains(t)) s += 2
            if (s == 0) { ok = false; break }
            score += s
        }
        if (ok) out.add(HelpHit(a, score, snippetOf(a, tokens)))
    }
    out.sortByDescending { it.score }
    return out
}

private fun hl(text: String, tokens: List<String>, color: Color): AnnotatedString {
    if (tokens.isEmpty() || text.isEmpty()) return AnnotatedString(text)
    val n = normH(text)
    val marks = BooleanArray(text.length)
    for (t in tokens) {
        var i = n.indexOf(t)
        while (i >= 0) {
            val end = minOf(i + t.length, text.length)
            var k = i
            while (k < end) { marks[k] = true; k++ }
            i = n.indexOf(t, i + 1)
        }
    }
    return buildAnnotatedString {
        var i = 0
        while (i < text.length) {
            var j = i
            while (j < text.length && marks[j] == marks[i]) j++
            val part = text.substring(i, j)
            if (marks[i]) {
                withStyle(SpanStyle(background = color)) { append(part) }
            } else {
                append(part)
            }
            i = j
        }
    }
}


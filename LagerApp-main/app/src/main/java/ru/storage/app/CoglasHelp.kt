        val a = HELP_ARTICLES.firstOrNull { it.id == id } ?: return
        val cur = articleId
        if (push && cur != null) trail.add(cur)
        articleId = id
        chapterId = a.chapter
        focus.clearFocus()
    }

    val goBack: () -> Unit = {
        if (articleId != null) {
            if (trail.isNotEmpty()) {
                articleId = trail.removeAt(trail.size - 1)
            } else {
                articleId = null
            }
        } else if (q.isNotBlank()) {
            q = ""
        } else if (chapterId != null) {
            chapterId = null
        } else {
            onClose()
        }
    }
    BackHandler(onBack = goBack)

    val tokens = helpTokens(q)
    val searching = q.isNotBlank() && articleId == null

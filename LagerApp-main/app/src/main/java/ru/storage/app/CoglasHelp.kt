                    )
                    if (hits.isEmpty()) {
                        Text("Попробуйте другое слово или часть слова (например, «пал» вместо «паллета»), либо откройте оглавление: очистите строку поиска.")
                    }
                }
                items(hits) { h ->
                    Card(
                        Modifier.fillMaxWidth().padding(bottom = 8.dp).clickable { openArticle(h.a.id, false) },
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                    ) {
                        Column(Modifier.padding(12.dp)) {
                            Text(chapterTitle(h.a.chapter), fontSize = 12.sp, color = MaterialTheme.colorScheme.primary)
                            Text(hl(h.a.title, tokens, mark), fontSize = 16.sp, fontWeight = FontWeight.Bold)
                            Spacer(Modifier.height(4.dp))
                            Text(hl(h.snippet, tokens, mark), fontSize = 14.sp, maxLines = 4, overflow = TextOverflow.Ellipsis)
                        }
                    }
                }
            }
        } else if (article != null) {
            // ---------------------------------------------------------------- статья
            val siblings = HELP_ARTICLES.filter { it.chapter == article.chapter }
            val pos = siblings.indexOfFirst { it.id == article.id }
            val prev = if (pos > 0) siblings[pos - 1] else null
            val next = if (pos >= 0 && pos < siblings.size - 1) siblings[pos + 1] else null
            LazyColumn(Modifier.fillMaxSize(), contentPadding = androidx.compose.foundation.layout.PaddingValues(16.dp)) {
                item {
                    Text(chapterTitle(article.chapter) + "  ›  статья " + (pos + 1) + " из " + siblings.size, fontSize = 12.sp, color = MaterialTheme.colorScheme.primary)
                    Spacer(Modifier.height(4.dp))
                    Text(hl(article.title, tokens, mark), fontSize = 22.sp, fontWeight = FontWeight.Bold)
                    Spacer(Modifier.height(8.dp))
                    Text(hl(article.lead, tokens, mark), fontSize = 15.sp, fontWeight = FontWeight.Medium, lineHeight = 22.sp)
                    Spacer(Modifier.height(4.dp))
                    HorizontalDivider(Modifier.padding(vertical = 8.dp))
                }
                item {
                    var n = 0
                    Column(Modifier.fillMaxWidth()) {
                        for (b in article.blocks) {
                            if (b.kind == 's') n++ else n = 0
                            when (b.kind) {
                                'h' -> Text(b.text, fontSize = 17.sp, fontWeight = FontWeight.Bold, modifier = Modifier.padding(top = 14.dp, bottom = 6.dp))
                                's' -> Row(Modifier.fillMaxWidth().padding(vertical = 4.dp), verticalAlignment = Alignment.Top) {
                                    Box(
                                        Modifier.size(26.dp).background(MaterialTheme.colorScheme.primary, RoundedCornerShape(13.dp)),
                                        contentAlignment = Alignment.Center
                                    ) {
                                        Text(n.toString(), color = MaterialTheme.colorScheme.onPrimary, fontSize = 13.sp, fontWeight = FontWeight.Bold)
                                    }
                                    Spacer(Modifier.width(10.dp))
                                    Text(hl(b.text, tokens, mark), fontSize = 15.sp, lineHeight = 22.sp, modifier = Modifier.weight(1f))
                                }
                                'n' -> HelpBox("Заметка", b.text, MaterialTheme.colorScheme.secondaryContainer, MaterialTheme.colorScheme.onSecondaryContainer, tokens, mark)
                                't' -> HelpBox("Совет", b.text, MaterialTheme.colorScheme.tertiaryContainer, MaterialTheme.colorScheme.onTertiaryContainer, tokens, mark)
                                'w' -> HelpBox("Важно", b.text, MaterialTheme.colorScheme.errorContainer, MaterialTheme.colorScheme.onErrorContainer, tokens, mark)
                                else -> Text(hl(b.text, tokens, mark), fontSize = 15.sp, lineHeight = 22.sp, modifier = Modifier.padding(vertical = 4.dp))
                            }
                        }
                    }
                }
                if (article.see.isNotEmpty()) {
                    item {
                        HorizontalDivider(Modifier.padding(vertical = 12.dp))
                        Text("См. также", fontSize = 16.sp, fontWeight = FontWeight.Bold)
                        for (id in article.see) {
                            val s = HELP_ARTICLES.firstOrNull { it.id == id }
                            if (s != null) {
                                Text(
                                    "›  " + s.title,
                                    color = MaterialTheme.colorScheme.primary, fontSize = 15.sp,
                                    modifier = Modifier.fillMaxWidth().clickable { openArticle(s.id, true) }.padding(vertical = 8.dp)
                                )
                            }
                        }
                    }
                }
                item {
                    Spacer(Modifier.height(12.dp))
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        if (prev != null) {
                            OutlinedButton(onClick = { openArticle(prev.id, false) }, modifier = Modifier.weight(1f)) {
                                Text("‹ " + prev.title, maxLines = 2, overflow = TextOverflow.Ellipsis, fontSize = 12.sp)
                            }
                        }
                        if (next != null) {
                            OutlinedButton(onClick = { openArticle(next.id, false) }, modifier = Modifier.weight(1f)) {
                                Text(next.title + " ›", maxLines = 2, overflow = TextOverflow.Ellipsis, fontSize = 12.sp)
                            }
                        }
                    }
                    Spacer(Modifier.height(24.dp))
                }
            }
        } else if (chapterId != null) {
            // ---------------------------------------------------------------- оглавление главы
            val list = HELP_ARTICLES.filter { it.chapter == chapterId }
            val ch = HELP_CHAPTERS.firstOrNull { it.id == chapterId }
            LazyColumn(Modifier.fillMaxSize(), contentPadding = androidx.compose.foundation.layout.PaddingValues(12.dp)) {
                item {
                    if (ch != null) Text(ch.desc, fontSize = 14.sp, modifier = Modifier.padding(bottom = 10.dp))
                }
                items(list) { a ->
                    Card(
                        Modifier.fillMaxWidth().padding(bottom = 8.dp).clickable { openArticle(a.id, false) },
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                    ) {
                        Column(Modifier.padding(12.dp)) {
                            Text(a.title, fontSize = 16.sp, fontWeight = FontWeight.Bold)
                            Spacer(Modifier.height(2.dp))
                            Text(a.lead, fontSize = 13.sp, maxLines = 2, overflow = TextOverflow.Ellipsis, color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                    }
                }
            }
        } else {
            // ---------------------------------------------------------------- главная страница справки
            LazyColumn(Modifier.fillMaxSize(), contentPadding = androidx.compose.foundation.layout.PaddingValues(12.dp)) {
                item {
                    Text(
                        "Здесь подробно объясняется работа с сайтом Coglas: что нажимать, что сканировать и что означают сообщения. Введите слово в строку поиска или выберите главу.",
                        fontSize = 14.sp, lineHeight = 20.sp, modifier = Modifier.padding(bottom = 12.dp)
                    )
                    Text("Быстрый старт", fontSize = 16.sp, fontWeight = FontWeight.Bold)
                    for (id in listOf("site", "nav", "lang", "scan", "in-overview")) {
                        val s = HELP_ARTICLES.firstOrNull { it.id == id }
                        if (s != null) {
                            Text(
                                "›  " + s.title,
                                color = MaterialTheme.colorScheme.primary, fontSize = 15.sp,
                                modifier = Modifier.fillMaxWidth().clickable { openArticle(s.id, false) }.padding(vertical = 8.dp)
                            )
                        }
                    }
                    Spacer(Modifier.height(12.dp))
                    Text("Главы", fontSize = 16.sp, fontWeight = FontWeight.Bold, modifier = Modifier.padding(bottom = 8.dp))
                }
                items(HELP_CHAPTERS) { c ->
                    val cnt = HELP_ARTICLES.count { it.chapter == c.id }
                    Card(
                        Modifier.fillMaxWidth().padding(bottom = 8.dp).clickable { chapterId = c.id },
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                    ) {
                        Column(Modifier.padding(12.dp)) {
                            Text(c.title + "  (" + cnt + ")", fontSize = 17.sp, fontWeight = FontWeight.Bold)
                            Spacer(Modifier.height(2.dp))
                            Text(c.desc, fontSize = 13.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun HelpBox(label: String, text: String, bg: Color, fg: Color, tokens: List<String>, mark: Color) {
    Column(
        Modifier.fillMaxWidth().padding(vertical = 6.dp)
            .background(bg, RoundedCornerShape(8.dp)).padding(10.dp)
    ) {
        Text(label, color = fg, fontSize = 12.sp, fontWeight = FontWeight.Bold)
        Spacer(Modifier.height(2.dp))
        Text(hl(text, tokens, mark), color = fg, fontSize = 14.sp, lineHeight = 20.sp)
    }
}
